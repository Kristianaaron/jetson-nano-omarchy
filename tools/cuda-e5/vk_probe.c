// G1: NVIDIA R36 Vulkan on GM20B through nvgpu. No window system and no VK_KHR_display.
// Enumerates physical devices, creates a device with a compute queue, runs one compute shader
// (y[i] = 2*x[i] + 1 over 1 Mi floats) and checks every element on the CPU. Exit 0 = pass.
// The SPIR-V is the compiled form of:
//   #version 450
//   layout(local_size_x = 256) in;
//   layout(std430, binding = 0) buffer X { float x[]; };
//   layout(std430, binding = 1) buffer Y { float y[]; };
//   void main() { uint i = gl_GlobalInvocationID.x; y[i] = 2.0 * x[i] + 1.0; }
#include <vulkan/vulkan.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#define N (1u << 20)
#include "vk_probe_spv.h" /* static const uint32_t kSpv[]; generated by glslangValidator */

#define VK(call)                                                       \
  do {                                                                 \
    VkResult r_ = (call);                                              \
    if (r_ != VK_SUCCESS) {                                            \
      printf("FAIL %s: VkResult %d\n", #call, (int)r_);                \
      return 1;                                                        \
    }                                                                  \
    printf("ok   %s\n", #call);                                        \
  } while (0)

static uint32_t find_mem(VkPhysicalDevice pd, uint32_t bits, VkMemoryPropertyFlags want)
{
  VkPhysicalDeviceMemoryProperties mp;
  vkGetPhysicalDeviceMemoryProperties(pd, &mp);
  for (uint32_t i = 0; i < mp.memoryTypeCount; i++)
    if ((bits & (1u << i)) && (mp.memoryTypes[i].propertyFlags & want) == want)
      return i;
  return UINT32_MAX;
}

int main(void)
{
  VkApplicationInfo app = {.sType = VK_STRUCTURE_TYPE_APPLICATION_INFO,
                           .pApplicationName = "vk_probe", .apiVersion = VK_API_VERSION_1_1};
  VkInstanceCreateInfo ici = {.sType = VK_STRUCTURE_TYPE_INSTANCE_CREATE_INFO, .pApplicationInfo = &app};
  VkInstance inst;
  VK(vkCreateInstance(&ici, NULL, &inst));

  uint32_t n = 0;
  VK(vkEnumeratePhysicalDevices(inst, &n, NULL));
  printf("physical devices: %u\n", n);
  if (n == 0)
    return 1;
  VkPhysicalDevice pds[4];
  if (n > 4) n = 4;
  VK(vkEnumeratePhysicalDevices(inst, &n, pds));
  VkPhysicalDevice pd = pds[0];
  VkPhysicalDeviceProperties p;
  vkGetPhysicalDeviceProperties(pd, &p);
  printf("device: %s, Vulkan %u.%u.%u, driver 0x%x, vendor 0x%x, device 0x%x, type %d\n", p.deviceName,
         VK_API_VERSION_MAJOR(p.apiVersion), VK_API_VERSION_MINOR(p.apiVersion),
         VK_API_VERSION_PATCH(p.apiVersion), p.driverVersion, p.vendorID, p.deviceID, p.deviceType);

  uint32_t en = 0;
  vkEnumerateDeviceExtensionProperties(pd, NULL, &en, NULL);
  VkExtensionProperties *ext = calloc(en, sizeof(*ext));
  vkEnumerateDeviceExtensionProperties(pd, NULL, &en, ext);
  printf("device extensions: %u\n", en);
  for (uint32_t i = 0; i < en; i++)
    if (strstr(ext[i].extensionName, "external") || strstr(ext[i].extensionName, "dma_buf") ||
        strstr(ext[i].extensionName, "drm") || strstr(ext[i].extensionName, "modifier") ||
        strstr(ext[i].extensionName, "swapchain") || strstr(ext[i].extensionName, "timeline") ||
        strstr(ext[i].extensionName, "fd"))
      printf("  ext %s\n", ext[i].extensionName);
  free(ext);

  uint32_t qn = 0, qf = UINT32_MAX;
  vkGetPhysicalDeviceQueueFamilyProperties(pd, &qn, NULL);
  VkQueueFamilyProperties qp[8];
  if (qn > 8) qn = 8;
  vkGetPhysicalDeviceQueueFamilyProperties(pd, &qn, qp);
  for (uint32_t i = 0; i < qn; i++) {
    printf("queue family %u: flags 0x%x count %u\n", i, qp[i].queueFlags, qp[i].queueCount);
    if (qf == UINT32_MAX && (qp[i].queueFlags & VK_QUEUE_COMPUTE_BIT))
      qf = i;
  }
  if (qf == UINT32_MAX)
    return 1;

  float prio = 1.0f;
  VkDeviceQueueCreateInfo qci = {.sType = VK_STRUCTURE_TYPE_DEVICE_QUEUE_CREATE_INFO,
                                 .queueFamilyIndex = qf, .queueCount = 1, .pQueuePriorities = &prio};
  VkDeviceCreateInfo dci = {.sType = VK_STRUCTURE_TYPE_DEVICE_CREATE_INFO, .queueCreateInfoCount = 1,
                            .pQueueCreateInfos = &qci};
  VkDevice dev;
  VK(vkCreateDevice(pd, &dci, NULL, &dev));
  VkQueue q;
  vkGetDeviceQueue(dev, qf, 0, &q);

  VkBuffer buf[2];
  VkDeviceMemory mem[2];
  float *map[2];
  for (int b = 0; b < 2; b++) {
    VkBufferCreateInfo bci = {.sType = VK_STRUCTURE_TYPE_BUFFER_CREATE_INFO, .size = N * sizeof(float),
                              .usage = VK_BUFFER_USAGE_STORAGE_BUFFER_BIT};
    VK(vkCreateBuffer(dev, &bci, NULL, &buf[b]));
    VkMemoryRequirements mr;
    vkGetBufferMemoryRequirements(dev, buf[b], &mr);
    uint32_t mt = find_mem(pd, mr.memoryTypeBits,
                           VK_MEMORY_PROPERTY_HOST_VISIBLE_BIT | VK_MEMORY_PROPERTY_HOST_COHERENT_BIT);
    if (mt == UINT32_MAX) {
      printf("FAIL no host-visible coherent memory type\n");
      return 1;
    }
    VkMemoryAllocateInfo mai = {.sType = VK_STRUCTURE_TYPE_MEMORY_ALLOCATE_INFO,
                                .allocationSize = mr.size, .memoryTypeIndex = mt};
    VK(vkAllocateMemory(dev, &mai, NULL, &mem[b]));
    VK(vkBindBufferMemory(dev, buf[b], mem[b], 0));
    VK(vkMapMemory(dev, mem[b], 0, VK_WHOLE_SIZE, 0, (void **)&map[b]));
  }
  for (uint32_t i = 0; i < N; i++) {
    map[0][i] = (float)(i % 1000) * 0.25f;
    map[1][i] = -1.0f;
  }

  VkShaderModuleCreateInfo smi = {.sType = VK_STRUCTURE_TYPE_SHADER_MODULE_CREATE_INFO,
                                  .codeSize = sizeof(kSpv), .pCode = kSpv};
  VkShaderModule sm;
  VK(vkCreateShaderModule(dev, &smi, NULL, &sm));
  VkDescriptorSetLayoutBinding lb[2] = {
      {.binding = 0, .descriptorType = VK_DESCRIPTOR_TYPE_STORAGE_BUFFER, .descriptorCount = 1,
       .stageFlags = VK_SHADER_STAGE_COMPUTE_BIT},
      {.binding = 1, .descriptorType = VK_DESCRIPTOR_TYPE_STORAGE_BUFFER, .descriptorCount = 1,
       .stageFlags = VK_SHADER_STAGE_COMPUTE_BIT}};
  VkDescriptorSetLayoutCreateInfo dli = {.sType = VK_STRUCTURE_TYPE_DESCRIPTOR_SET_LAYOUT_CREATE_INFO,
                                         .bindingCount = 2, .pBindings = lb};
  VkDescriptorSetLayout dsl;
  VK(vkCreateDescriptorSetLayout(dev, &dli, NULL, &dsl));
  VkPipelineLayoutCreateInfo pli = {.sType = VK_STRUCTURE_TYPE_PIPELINE_LAYOUT_CREATE_INFO,
                                    .setLayoutCount = 1, .pSetLayouts = &dsl};
  VkPipelineLayout pl;
  VK(vkCreatePipelineLayout(dev, &pli, NULL, &pl));
  VkComputePipelineCreateInfo cpi = {
      .sType = VK_STRUCTURE_TYPE_COMPUTE_PIPELINE_CREATE_INFO,
      .stage = {.sType = VK_STRUCTURE_TYPE_PIPELINE_SHADER_STAGE_CREATE_INFO,
                .stage = VK_SHADER_STAGE_COMPUTE_BIT, .module = sm, .pName = "main"},
      .layout = pl};
  VkPipeline pipe;
  VK(vkCreateComputePipelines(dev, VK_NULL_HANDLE, 1, &cpi, NULL, &pipe));

  VkDescriptorPoolSize ps = {.type = VK_DESCRIPTOR_TYPE_STORAGE_BUFFER, .descriptorCount = 2};
  VkDescriptorPoolCreateInfo dpi = {.sType = VK_STRUCTURE_TYPE_DESCRIPTOR_POOL_CREATE_INFO, .maxSets = 1,
                                    .poolSizeCount = 1, .pPoolSizes = &ps};
  VkDescriptorPool dp;
  VK(vkCreateDescriptorPool(dev, &dpi, NULL, &dp));
  VkDescriptorSetAllocateInfo dsa = {.sType = VK_STRUCTURE_TYPE_DESCRIPTOR_SET_ALLOCATE_INFO,
                                     .descriptorPool = dp, .descriptorSetCount = 1, .pSetLayouts = &dsl};
  VkDescriptorSet ds;
  VK(vkAllocateDescriptorSets(dev, &dsa, &ds));
  VkDescriptorBufferInfo bi[2] = {{buf[0], 0, VK_WHOLE_SIZE}, {buf[1], 0, VK_WHOLE_SIZE}};
  VkWriteDescriptorSet w[2];
  for (int b = 0; b < 2; b++)
    w[b] = (VkWriteDescriptorSet){.sType = VK_STRUCTURE_TYPE_WRITE_DESCRIPTOR_SET, .dstSet = ds,
                                  .dstBinding = (uint32_t)b, .descriptorCount = 1,
                                  .descriptorType = VK_DESCRIPTOR_TYPE_STORAGE_BUFFER, .pBufferInfo = &bi[b]};
  vkUpdateDescriptorSets(dev, 2, w, 0, NULL);

  VkCommandPoolCreateInfo cpci = {.sType = VK_STRUCTURE_TYPE_COMMAND_POOL_CREATE_INFO, .queueFamilyIndex = qf};
  VkCommandPool cp;
  VK(vkCreateCommandPool(dev, &cpci, NULL, &cp));
  VkCommandBufferAllocateInfo cba = {.sType = VK_STRUCTURE_TYPE_COMMAND_BUFFER_ALLOCATE_INFO,
                                     .commandPool = cp, .level = VK_COMMAND_BUFFER_LEVEL_PRIMARY,
                                     .commandBufferCount = 1};
  VkCommandBuffer cb;
  VK(vkAllocateCommandBuffers(dev, &cba, &cb));
  VkCommandBufferBeginInfo cbi = {.sType = VK_STRUCTURE_TYPE_COMMAND_BUFFER_BEGIN_INFO};
  VK(vkBeginCommandBuffer(cb, &cbi));
  vkCmdBindPipeline(cb, VK_PIPELINE_BIND_POINT_COMPUTE, pipe);
  vkCmdBindDescriptorSets(cb, VK_PIPELINE_BIND_POINT_COMPUTE, pl, 0, 1, &ds, 0, NULL);
  vkCmdDispatch(cb, N / 256, 1, 1);
  VK(vkEndCommandBuffer(cb));
  VkSubmitInfo si = {.sType = VK_STRUCTURE_TYPE_SUBMIT_INFO, .commandBufferCount = 1, .pCommandBuffers = &cb};
  VK(vkQueueSubmit(q, 1, &si, VK_NULL_HANDLE));
  VK(vkQueueWaitIdle(q));

  uint32_t bad = 0;
  for (uint32_t i = 0; i < N; i++)
    if (map[1][i] != 2.0f * map[0][i] + 1.0f)
      bad++;
  printf("compute shader: %u wrong of %u\n", bad, N);
  printf(bad ? "G1 FAIL\n" : "G1 PASS\n");
  vkDeviceWaitIdle(dev);
  vkDestroyDevice(dev, NULL);
  vkDestroyInstance(inst, NULL);
  return bad ? 1 : 0;
}
